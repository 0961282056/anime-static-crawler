"""Deterministically assemble ordered frontend modules without a runtime loader."""

from __future__ import annotations

import json
import re
from pathlib import Path

from services.atomic_io import atomic_write_text


def render_frontend_bundle(root: Path) -> str:
    source = root / "frontend"
    manifest = json.loads((source / "modules.json").read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 1 or not manifest.get("modules"):
        raise ValueError("Invalid frontend module manifest")
    seen, files, parts = set(), set(), []
    for module in manifest["modules"]:
        name, file = module["name"], module["file"]
        if (
            not re.fullmatch(r"[a-z][a-z-]*", name)
            or not re.fullmatch(r"[a-z][a-z-]*\.js", file)
            or name in seen
            or file in files
            or not isinstance(module.get("requires"), list)
            or any(dependency not in seen for dependency in module["requires"])
        ):
            raise ValueError(f"Invalid or unordered frontend module: {name}")
        seen.add(name)
        files.add(file)
        content = (source / file).read_text(encoding="utf-8").rstrip()
        parts.append(f"// Module: {name}\n{content}\n")
    actual = {path.name for path in source.glob("*.js")}
    if actual != files:
        raise ValueError("Frontend source files do not match the module manifest")
    return (
        "// Generated by python manage.py build-frontend; edit frontend/*.js.\n"
        "(() => {\n'use strict';\n\n" + "\n".join(parts) + "\n})();\n"
    )


def build_frontend_bundle(root: Path) -> None:
    atomic_write_text(root / "static/js/main.js", render_frontend_bundle(root))


def verify_frontend_bundle(root: Path) -> None:
    # Isolated static-build fixtures can omit this optional source tree.
    if not (root / "frontend").exists():
        return
    target = root / "static/js/main.js"
    if not target.is_file() or target.read_text(
        encoding="utf-8"
    ) != render_frontend_bundle(root):
        raise ValueError(
            "Frontend bundle is stale; run python manage.py build-frontend"
        )
